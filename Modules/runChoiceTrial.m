function trial = runChoiceTrial( ...
    P, T, ChoiceSet, condition, ...
    ChoiceLayout, QuestionnaireLayout, questionFiles)

% runChoiceTrial  Run one complete choice-task trial.
%
%   trial = runChoiceTrial( ...
%       P, T, ChoiceSet, condition, ...
%       ChoiceLayout, QuestionnaireLayout, questionFiles)
%
%   Trial sequence:
%
%       Fixation
%       Exposure
%       Mask
%       Choice fixation
%       Choice
%       Questionnaire
%
%   If no valid choice response is made before the choice timeout,
%   the trial is marked as missed and the questionnaire is skipped.
%
%   Inputs:
%       P                   - Parameter structure.
%       T                   - Task structure.
%       ChoiceSet           - Vector containing stimulus image IDs.
%       condition           - Condition label for the current trial.
%       ChoiceLayout        - Pixel-based choice-task layout.
%       QuestionnaireLayout - Pixel-based questionnaire layout.
%       questionFiles       - Questionnaire image file paths.
%
%   Output:
%       trial.choiceSet
%       trial.condition
%       trial.positions
%       trial.response
%       trial.selectedImage
%       trial.RT
%       trial.question.response
%       trial.question.RT


%% ==============================================================
% Initialize Trial Result
% ==============================================================

trial = struct( ...
    'choiceSet',     ChoiceSet, ...
    'condition',     condition, ...
    'positions',     [], ...
    'response',      [], ...
    'selectedImage', NaN, ...
    'RT',            NaN, ...
    'question',      struct( ...
        'response', nan(1, P.Questionnaire.nQuestions), ...
        'RT',       nan(1, P.Questionnaire.nQuestions)));


stimulusIDs = ChoiceSet;


%% ==============================================================
% Assign Stimuli to Spatial Locations
% ==============================================================

positions = randomizeChoicePositions( ...
    ChoiceLayout, ...
    numel(stimulusIDs));


trial.positions = positions;


%% ==============================================================
% Fixation
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


% Fixation tile
Screen( ...
    'FillRect', ...
    T.window, ...
    P.Choice.Layout.maskColor, ...
    ChoiceLayout.fixation);


% Horizontal fixation line
Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.horizontal(1), ...
    ChoiceLayout.fixationCross.horizontal(2), ...
    ChoiceLayout.fixationCross.horizontal(3), ...
    ChoiceLayout.fixationCross.horizontal(4), ...
    P.Choice.Layout.fixationCrossWidth);


% Vertical fixation line
Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.vertical(1), ...
    ChoiceLayout.fixationCross.vertical(2), ...
    ChoiceLayout.fixationCross.vertical(3), ...
    ChoiceLayout.fixationCross.vertical(4), ...
    P.Choice.Layout.fixationCrossWidth);


Screen('Flip', T.window);

WaitSecs(P.Choice.fixationDuration);


%% ==============================================================
% Exposure
% ==============================================================

drawChoiceSet( ...
    P, ...
    T, ...
    stimulusIDs, ...
    ChoiceLayout, ...
    positions);


Screen('Flip', T.window);

WaitSecs(P.Choice.exposureDuration);


%% ==============================================================
% Mask
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


% ChoiceLayout.rect is nLocations x 4.
% Screen expects multiple rectangles as 4 x nLocations.
Screen( ...
    'FillRect', ...
    T.window, ...
    P.Choice.Layout.maskColor, ...
    ChoiceLayout.rect');


Screen('Flip', T.window);

WaitSecs(P.Choice.maskDuration);


%% ==============================================================
% Choice Fixation
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


% Fixation border
Screen( ...
    'FrameRect', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixation, ...
    P.Choice.Layout.fixationBorderWidth);


% Horizontal fixation line
Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.horizontal(1), ...
    ChoiceLayout.fixationCross.horizontal(2), ...
    ChoiceLayout.fixationCross.horizontal(3), ...
    ChoiceLayout.fixationCross.horizontal(4), ...
    P.Choice.Layout.fixationCrossWidth);


% Vertical fixation line
Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.vertical(1), ...
    ChoiceLayout.fixationCross.vertical(2), ...
    ChoiceLayout.fixationCross.vertical(3), ...
    ChoiceLayout.fixationCross.vertical(4), ...
    P.Choice.Layout.fixationCrossWidth);


Screen('Flip', T.window);

WaitSecs(P.Choice.choiceFixationDuration);


%% ==============================================================
% Choice Screen
% ==============================================================

drawChoiceSet( ...
    P, ...
    T, ...
    stimulusIDs, ...
    ChoiceLayout, ...
    positions);


% Use the actual flip timestamp as the response-time origin.
choiceOnset = Screen('Flip', T.window);


%% ==============================================================
% Collect Choice Response
% ==============================================================

[response, RT] = collectChoiceResponse( ...
    T.window, ...
    ChoiceLayout, ...
    positions.stimulus, ...
    choiceOnset, ...
    P.Choice.choiceDuration);


trial.response = response;
trial.RT = RT;


%% ==============================================================
% Missed Trial
% ==============================================================

if isempty(response)

    trial.selectedImage = NaN;

    % Questionnaire fields already contain NaN values.
    % Skip the questionnaire for a missed choice.
    return;

end


%% ==============================================================
% Determine Selected Image
% ==============================================================

stimulusIndex = find( ...
    positions.stimulus == response, ...
    1, ...
    'first');


% This should never occur because collectChoiceResponse only accepts
% occupied stimulus locations. Keep this check to catch future errors.
if isempty(stimulusIndex)

    error( ...
        'Choice response location %d does not contain a stimulus.', ...
        response);

end


trial.selectedImage = stimulusIDs(stimulusIndex);


%% ==============================================================
% Questionnaire
% ==============================================================

[questionResponse, questionRT] = runQuestionnaire( ...
    P, ...
    T, ...
    QuestionnaireLayout, ...
    questionFiles);


trial.question.response = questionResponse;
trial.question.RT = questionRT;


end