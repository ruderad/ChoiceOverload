function trial = runChoiceTrial( ...
    P, T, ChoiceSet, condition, ...
    ChoiceLayout, QuestionnaireLayout, questionFiles)

% runChoiceTrial  Run one complete choice-task trial.
%
%   trial = runChoiceTrial( ...
%       P, T, ChoiceSet, condition, ...
%       ChoiceLayout, QuestionnaireLayout, questionFiles)
%
%   Trial sequence:
%
%       Fixation
%       Exposure
%       Mask
%       Choice fixation
%       Response phase
%       Questionnaire
%
%   Response phase:
%
%       Yellow fixation border
%           ->
%       Yellow hovered-stimulus border
%           ->
%       Green selected-stimulus border
%
%   No yellow highlighting is shown during exposure.
%
%   If no valid response is made before the choice timeout,
%   the questionnaire is skipped.


%% ==============================================================
% Initialize Trial Result
% ==============================================================

trial = struct( ...
    'choiceSet',     ChoiceSet, ...
    'condition',     condition, ...
    'positions',     [], ...
    'response',      [], ...
    'selectedImage', NaN, ...
    'RT',            NaN, ...
    'question',      struct( ...
        'response', nan(1, P.Questionnaire.nQuestions), ...
        'RT',       nan(1, P.Questionnaire.nQuestions)));


stimulusIDs = ChoiceSet;


%% ==============================================================
% Assign Stimuli to Spatial Locations
% ==============================================================

positions = randomizeChoicePositions( ...
    ChoiceLayout, ...
    numel(stimulusIDs));


trial.positions = positions;


%% ==============================================================
% Fixation
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


%% Fixation tile

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Choice.Layout.maskColor, ...
    ChoiceLayout.fixation);


%% Horizontal fixation line

Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.horizontal(1), ...
    ChoiceLayout.fixationCross.horizontal(2), ...
    ChoiceLayout.fixationCross.horizontal(3), ...
    ChoiceLayout.fixationCross.horizontal(4), ...
    P.Choice.Layout.fixationCrossWidth);


%% Vertical fixation line

Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.vertical(1), ...
    ChoiceLayout.fixationCross.vertical(2), ...
    ChoiceLayout.fixationCross.vertical(3), ...
    ChoiceLayout.fixationCross.vertical(4), ...
    P.Choice.Layout.fixationCrossWidth);


Screen('Flip', T.window);

WaitSecs(P.Choice.fixationDuration);


%% ==============================================================
% Exposure
% ==============================================================

% IMPORTANT:
% No yellow response highlighting exists in this phase.

drawChoiceSet( ...
    P, ...
    T, ...
    stimulusIDs, ...
    ChoiceLayout, ...
    positions);


Screen('Flip', T.window);

WaitSecs(P.Choice.exposureDuration);


%% ==============================================================
% Mask
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


Screen( ...
    'FillRect', ...
    T.window, ...
    P.Choice.Layout.maskColor, ...
    ChoiceLayout.rect');


Screen('Flip', T.window);

WaitSecs(P.Choice.maskDuration);


%% ==============================================================
% Choice Fixation
% ==============================================================

Screen( ...
    'FillRect', ...
    T.window, ...
    P.Screen.backgroundColor);


%% Fixation border

Screen( ...
    'FrameRect', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixation, ...
    P.Choice.Layout.fixationBorderWidth);


%% Horizontal fixation line

Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.horizontal(1), ...
    ChoiceLayout.fixationCross.horizontal(2), ...
    ChoiceLayout.fixationCross.horizontal(3), ...
    ChoiceLayout.fixationCross.horizontal(4), ...
    P.Choice.Layout.fixationCrossWidth);


%% Vertical fixation line

Screen( ...
    'DrawLine', ...
    T.window, ...
    P.Choice.Layout.fixationColor, ...
    ChoiceLayout.fixationCross.vertical(1), ...
    ChoiceLayout.fixationCross.vertical(2), ...
    ChoiceLayout.fixationCross.vertical(3), ...
    ChoiceLayout.fixationCross.vertical(4), ...
    P.Choice.Layout.fixationCrossWidth);


Screen('Flip', T.window);

WaitSecs(P.Choice.choiceFixationDuration);


%% ==============================================================
% Prepare Cached Response Display
% ==============================================================

% Create an offscreen window with the same dimensions as the
% participant's display.
responseBuffer = Screen( ...
    'OpenOffscreenWindow', ...
    T.window, ...
    P.Screen.backgroundColor);


% drawChoiceSet expects the target window inside T.
% Make a temporary copy that points to the offscreen window.
bufferT = T;
bufferT.window = responseBuffer;


% Draw the complete clean choice screen once.
drawChoiceSet( ...
    P, ...
    bufferT, ...
    stimulusIDs, ...
    ChoiceLayout, ...
    positions);


%% ==============================================================
% Response Phase
% ==============================================================

% Restore clean response display from the cached buffer.
Screen( ...
    'CopyWindow', ...
    responseBuffer, ...
    T.window);


% Response phase begins with the yellow border on fixation.
drawResponseHighlight( ...
    T.window, ...
    ChoiceLayout.fixation, ...
    P.Choice.Highlight.hoverColor, ...
    P.Choice.Highlight.borderWidth);


% Actual response onset timestamp.
choiceOnset = Screen('Flip', T.window);


%% ==============================================================
% Collect Choice Response
% ==============================================================

[response, RT] = collectChoiceResponse( ...
    T.window, ...
    responseBuffer, ...
    ChoiceLayout, ...
    positions.stimulus, ...
    choiceOnset, ...
    P.Choice.choiceDuration, ...
    P.Choice.Highlight);


trial.response = response;
trial.RT = RT;


%% ==============================================================
% Close Cached Response Display
% ==============================================================

Screen('Close', responseBuffer);


%% ==============================================================
% Missed Trial
% ==============================================================

if isempty(response)

    trial.selectedImage = NaN;

    % Questionnaire fields already contain NaN values.
    return;

end


%% ==============================================================
% Determine Selected Image
% ==============================================================

stimulusIndex = find( ...
    positions.stimulus == response, ...
    1, ...
    'first');


if isempty(stimulusIndex)

    error( ...
        'Choice response location %d does not contain a stimulus.', ...
        response);

end


trial.selectedImage = stimulusIDs(stimulusIndex);


%% ==============================================================
% Questionnaire
% ==============================================================

[questionResponse, questionRT] = runQuestionnaire( ...
    P, ...
    T, ...
    QuestionnaireLayout, ...
    questionFiles);


trial.question.response = questionResponse;
trial.question.RT = questionRT;


end